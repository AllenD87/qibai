#!/bin/sh
# 冷笑话技能（纯本地词库生成，无网络、无文件读写、零权限）。
# 合规设计（对齐 JokeAPI 的分类 + safe-mode 思路）：
#   - 只内置三类无伤害段子：谐音类 / 文字游戏类 / 反转类；
#   - 硬禁：地域/职业/疾病/性别/群体攻击梗，低俗梗，时政梗（词库入库前已逐条筛除）；
#   - 全龄友好，只许「一笑了之」，不许拿任何人开涮。
# 六道安全闸：①参数仅用于类别匹配与种子，不拼 shell 命令；②无路径逻辑；
#   ③无网络、无文件读取；④零权限不写文件；⑤无密钥；⑥空参默认随机输出，不报错。
set -u

ARGS="${QIBAI_SKILL_ARGS:-}"

# ---------- 抽取类别字段（sed 抽 JSON，失败降级纯文本；允许为空） ----------
CAT=$(printf '%s' "$ARGS" | sed -n 's/.*"category"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
if [ -z "$CAT" ]; then
  CAT=$(printf '%s' "$ARGS" | tr -d '{}[]"' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
fi

# ---------- 确定性随机种子 ----------
TS=$(date +%s)
HASH=$(printf '%s' "$ARGS" | cksum | cut -d' ' -f1)
[ -z "$HASH" ] && HASH=0
SEED=$((TS + HASH))

# ---------- 词库（每行一条，全龄无伤害；三条线：谐音/文字游戏/反转） ----------
PUN='
程序员最讨厌康熙的哪个儿子？答：胤禛——因为他总在 in ZEN（印真）状态里写 bug。
什么动物最容易滑倒？答：狐狸，因为它很「狡猾」（脚滑）。
哪种水果最爱忙工作？答：芒果，因为它是「忙果」。
谁出门总是迷路？答：麋鹿，因为它的名字就叫「迷路」。
咖啡和奶茶谁更有气场？答：咖啡，因为它有「咖」位。
虾和蚌考试都得满分，老师却说虾作弊，为什么？答：因为虾的分数是「瞎」写的。
什么蛋不能吃？答：零蛋——考试考出来的那种。
鸭子为什么走路摇摇摆摆？答：因为它一直没站稳过。
北极熊为什么不吃企鹅？答：一个住北极、一个住南极，想见也见不着。
'

WORD='
什么东西越洗越脏？答：水。
什么门永远关不上？答：球门。
什么布剪不断？答：瀑布。
冰变成水最快的方法是什么？答：去掉「冰」字的两点水。
什么车寸步难行？答：风车。
书店里买不到什么书？答：秘书。
大象的左耳朵最像什么？答：它的右耳朵。
为什么数学书总是看起来很忧郁？答：因为它有太多的问题。
什么东西明明是你的，别人却用得比你多？答：你的名字。
'

TWIST='
为什么企鹅的肚皮是白的？答：因为它手短，洗澡只能够到肚子。
大雁秋天为什么要飞到南方去？答：因为走过去太慢了。
一只蜗牛搬进了乌龟的房子，第二天乌龟大发雷霆，蜗牛委屈地说：别急呀，我刚装修好。
闹钟响了三遍我才起床——不是我懒，是床先动的手。
我对镜子说「你今天真好看」，镜子也说「你今天真好看」——后来才发现那是窗玻璃，它说的是街对面的人。
朋友问我：「你知道为什么你总找不到东西吗？」我说：「为什么？」他说：「因为你找它的时候，它也在找你，你们总是完美错过。」
老师问小明：「你的作业为什么让弟弟帮你写？」小明说：「妈妈说了，自己的事情自己做——所以我让弟弟做他的事情。」
今天我把闹钟关了继续睡，醒来一看：闹钟比我努力，它已经响了三遍，我只成功了一次。
小鱼问大鱼：「为什么大鱼总吃小鱼？」大鱼说：「不然呢？难道要我先下个馆子吗？」
'

# ---------- 按类别选池（空参=随机混合；点名未知类别=友好提示） ----------
if [ -z "$CAT" ]; then
  POOL=$(printf '%s\n%s\n%s\n' "$PUN" "$WORD" "$TWIST")
  POOL_NAME="混合"
else
  case "$CAT" in
    *谐音*)        POOL=$(printf '%s\n' "$PUN");   POOL_NAME="谐音类" ;;
    *文字*|*双关*) POOL=$(printf '%s\n' "$WORD");  POOL_NAME="文字游戏类" ;;
    *反转*)        POOL=$(printf '%s\n' "$TWIST"); POOL_NAME="反转类" ;;
    *)
      echo "这个类别我暂时没有收录。我目前会讲三类：谐音梗、文字游戏、反转类；或者说「随便讲一个」，我随机来。"
      exit 0
      ;;
  esac
fi

# ---------- 去空行并抽 1-3 条（去重） ----------
POOL=$(printf '%s\n' "$POOL" | grep .)
TOTAL=$(printf '%s\n' "$POOL" | grep -c .)
if [ "$TOTAL" -lt 1 ]; then
  echo "词库暂时缺货，稍后再试吧～"
  exit 0
fi

COUNT=$((1 + SEED % 3))
IDX1=$(( SEED % TOTAL ))
IDX2=$(( (SEED / 7) % TOTAL ))
IDX3=$(( (SEED / 13) % TOTAL ))
while [ "$IDX2" -eq "$IDX1" ]; do IDX2=$(( (IDX2 + 1) % TOTAL )); done
while [ "$IDX3" -eq "$IDX1" ] || [ "$IDX3" -eq "$IDX2" ]; do IDX3=$(( (IDX3 + 1) % TOTAL )); done

pick() { printf '%s\n' "$POOL" | sed -n "$(( $1 + 1 ))p"; }

echo "【冷笑话时间 · $POOL_NAME】（本地词库生成，一笑了之）"
echo "1. $(pick $IDX1)"
[ "$COUNT" -ge 2 ] && echo "2. $(pick $IDX2)"
[ "$COUNT" -ge 3 ] && echo "3. $(pick $IDX3)"
echo "---"
echo "希望笑到你啦～（全龄友好、无攻击无低俗；不好笑的话，换个类别我再来一段。）"

# v18.2 面板协议块：气泡笑话卡片
echo "@qibai-panel:begin"
echo "mode=bubble"
echo "title=冷笑话 · $POOL_NAME"
echo "html=<div>1. $(pick $IDX1)<br/>"
[ "$COUNT" -ge 2 ] && echo "2. $(pick $IDX2)<br/>"
[ "$COUNT" -ge 3 ] && echo "3. $(pick $IDX3)"
echo "</div>"
echo "@qibai-panel:end"
