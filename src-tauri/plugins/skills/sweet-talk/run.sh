#!/bin/sh
# 情话语录技能（纯本地三层词库规则生成，无网络、无文件读写副作用）。
# 六道安全闸：
# ①命令注入——参数仅做字符串匹配/字段抽取，绝不拼接进 shell 命令执行；
# ②路径遍历——本脚本不涉及任何路径操作；
# ③数据外泄——不读任何本地文件、不发起任何网络请求；
# ④越权——只读运行，不写/不删/不改任何文件；
# ⑤硬编码密钥——全文无任何密钥/API key/token；
# ⑥异常输入——空参/非法层级/非法条数给出友好中文提示后 exit 0，不抛栈。
set -u

ARGS="${QIBAI_SKILL_ARGS:-}"

# 从 JSON 参数抽字段（纯 sed，不依赖 jq）；抽不到时降级为纯文本兜底。
LEVEL=$(printf '%s' "$ARGS" | sed -n 's/.*"level"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
COUNT=$(printf '%s' "$ARGS" | sed -n 's/.*"count"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p')

# ---- 三层词库（全龄、尊重、无身体描写/无性暗示/无极端承诺）----
# L1 温和日常（7 条）
L1='今天也要记得吃好睡好，忙归忙，别亏待自己。
天气变凉了，出门记得加件衣服。
忙了一天啦，先喝口水，歇一会儿再继续。
晚饭别随便对付，好好吃饭是正经事。
今天的你也辛苦了，记得给自己一个小小的肯定。
久坐记得起来活动活动，伸个懒腰也好。
早点休息，睡个好觉，明天又是新的一天。'

# L2 俏皮轻松（7 条）
L2='你笑起来的时候，办公室的光都亮了几分。
今天效率这么高，是不是偷偷吃了什么好吃的？
夸你一句：你认真做事的样子还挺好看的。
听说认真生活的人运气都不会太差，比如你。
你今天状态不错呀，小表情都带着光。
跟你聊天挺开心的，这话我就只说一遍哦。
这么努力的你，值得一顿好饭奖励自己。'

# L3 深情但克制（7 条，不出现「永远/非你不嫁」类极端承诺）
L3='能和你一起把普通日子过好，就很珍贵。
慢慢来没关系，我会一直在旁边陪着你。
认识你之后，很多平常的小事都变得有意义了。
不用总逞强，累的时候可以靠过来歇一歇。
谢谢你愿意把日常的小事讲给我听。
和你一起慢慢变厉害，是我觉得很踏实的事。
那些一起度过的普通傍晚，回想起来都很暖。'

SEED=$(date +%s)

# 层级命中（大小写兼容；未填/填错 → 回退随机，不报错）
BANK=""
BNAME=""
case "$LEVEL" in
  *l1*|*L1*|*温和*|*日常*|*1*)  BANK="$L1"; BNAME="温和日常" ;;
  *l2*|*L2*|*俏皮*|*2*)         BANK="$L2"; BNAME="俏皮轻松" ;;
  *l3*|*L3*|*深情*|*3*)         BANK="$L3"; BNAME="深情克制" ;;
esac
if [ -z "$BANK" ]; then
  case $((SEED % 3)) in
    0) BANK="$L1"; BNAME="温和日常" ;;
    1) BANK="$L2"; BNAME="俏皮轻松" ;;
    2) BANK="$L3"; BNAME="深情克制" ;;
  esac
fi

# 条数：默认 1；非法值夹回 1-3
N=1
if [ -n "$COUNT" ]; then
  if [ "$COUNT" -gt 3 ]; then N=3; elif [ "$COUNT" -lt 1 ]; then N=1; else N="$COUNT"; fi
fi

# 按确定性偏移取行（步长 5 与 7 条词库互质，1-3 条互不撞车）
i=1
ALL=""
echo "【$BNAME · 情话语录】"
while [ "$i" -le "$N" ]; do
  LINE_NO=$((1 + (SEED + i * 5) % 7))
  LINE=$(printf '%s\n' "$BANK" | sed -n "${LINE_NO}p")
  ALL="$ALL<li>$LINE</li>
"
  printf '· %s\n' "$LINE"
  i=$((i + 1))
done
echo "---"
echo "内容合规：全龄、无擦边。适合发给亲近的人；对方情绪低落时，先好好问候比情话更重要。"
echo "（本地词库生成，未联网、未改动任何文件。）"
# v18.2 面板协议块：气泡情话卡片
echo "@qibai-panel:begin"
echo "mode=bubble"
echo "title=$BNAME · 情话语录"
echo "html=<div><ul>"
printf '%s' "$ALL"
echo "</ul><p><small>全龄、无擦边；本地词库生成，未联网。</small></p></div>"
echo "@qibai-panel:end"