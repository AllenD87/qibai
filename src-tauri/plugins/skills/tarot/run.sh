#!/bin/sh
# 塔罗占卜技能（纯本地规则生成，无网络、无文件读写、零权限）。
# 安全设计（对照 trailofbits let-fate-decide 的反迷信原则）：
#   - 抽牌由脚本确定性随机完成（时间戳 + 参数校验和为种子），绝不允许模型凭感觉口述一张牌凑数；
#   - 牌面不凌驾任何安全规则；一个问题只抽一次；
#   - 解读温和正向、不绝对化预测、不涉医疗/财务/法律建议；
#   - 娱乐免责声明固定输出在末尾。
# 六道安全闸：①参数仅用于字符串展示与种子计算，不拼 shell 命令；②无路径逻辑；
#   ③无网络、无文件读取，无外泄；④只读零权限，不写任何文件；⑤无密钥；⑥空参也可默认抽牌，优雅。
set -u

ARGS="${QIBAI_SKILL_ARGS:-}"

# ---------- 抽取问题字段（sed 抽 JSON，失败降级纯文本；允许为空） ----------
QUESTION=$(printf '%s' "$ARGS" | sed -n 's/.*"question"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
if [ -z "$QUESTION" ]; then
  QUESTION=$(printf '%s' "$ARGS" | sed -n 's/.*"text"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
fi
if [ -z "$QUESTION" ]; then
  QUESTION=$(printf '%s' "$ARGS" | tr -d '{}[]"' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
fi

# ---------- 确定性随机种子：时间戳 + 参数校验和（绝不靠 LLM「凭感觉」抽牌） ----------
TS=$(date +%s)
HASH=$(printf '%s' "$ARGS" | cksum | cut -d' ' -f1)
[ -z "$HASH" ] && HASH=0
SEED=$((TS + HASH))

# ---------- 22 张大阿卡纳（Rider-Waite-Smith 传统命名，中文） ----------
CARDS="愚者 魔术师 女祭司 女皇 皇帝 教皇 恋人 战车 力量 隐士 命运之轮 正义 倒吊人 死神 节制 恶魔 高塔 星星 月亮 太阳 审判 世界"

card_name() {
  i=0
  for c in $CARDS; do
    if [ "$i" -eq "$1" ]; then echo "$c"; return; fi
    i=$((i + 1))
  done
  echo "愚者"
}

# 解读词库：U=正位 / R=逆位（逆位=延迟、内化、需要慢一点，不是「凶」）
interpret() {
  case "$1" in
    0)  U="新的开始就在眼前，带着好奇心轻装上阵，小步探索就好。"
        R="别急着出发，先花两分钟理清方向，会走得更稳。" ;;
    1)  U="你手边的资源其实够用，把已有工具用起来，事情会顺很多。"
        R="想法很多但还没落地，先挑一件最小的做起来。" ;;
    2)  U="答案在你心里，安静下来听听自己的直觉。"
        R="信息有点杂，先把外界声音放一放，再做决定。" ;;
    3)  U="适合照顾自己与身边人，温柔的氛围会带来好状态。"
        R="别太操劳，留一点时间给自己休息充电。" ;;
    4)  U="立好规矩与计划，按部就班推进，效率会很高。"
        R="计划可以灵活一点，太硬反而容易卡住。" ;;
    5)  U="向有经验的人请教，或翻翻旧方法，会有新启发。"
        R="别人的建议仅供参考，最终按自己的节奏来。" ;;
    6)  U="重要关系值得用心沟通，坦诚交流会加分。"
        R="有分歧时先听对方说完，再表达自己。" ;;
    7)  U="方向感清晰，坚持推进，阻力会一点点变小。"
        R="同时想冲太多方向，先选一条主攻。" ;;
    8)  U="温柔而坚定地处理难题，耐心比强硬更有用。"
        R="有点累了，先照顾情绪，再处理事情。" ;;
    9)  U="适合独处复盘，把想法整理清楚再出发。"
        R="别一个人硬扛，找信任的人聊聊会轻松很多。" ;;
    10) U="节奏正在转好，顺势而为，保持开放。"
        R="有些变化不在计划内，稳住心态就好。" ;;
    11) U="公平客观地看待这件事，把账算清楚再行动。"
        R="别急着下判断，先把事实摆全。" ;;
    12) U="换个角度看问题，卡住的地方会突然通透。"
        R="暂停不是浪费，是在等更好的时机。" ;;
    13) U="一段旧的阶段正在自然收尾，告别之后空间更大。"
        R="有些过去还没放下，轻轻整理，再继续往前走。" ;;
    14) U="慢慢来，把节奏调匀，事情会越来越顺。"
        R="最近有点赶，刻意慢下来反而更高效。" ;;
    15) U="看看有没有小习惯在悄悄消耗你，调整一点就能松绑。"
        R="不必对自己太苛刻，松开一点也没关系。" ;;
    16) U="旧结构松动未必是坏事，清理之后会更清爽。"
        R="小预兆已经出现，提前整理一下会更从容。" ;;
    17) U="希望感在靠近，许个小愿望，一步步靠近它。"
        R="先照顾好心情，光亮会慢慢回来。" ;;
    18) U="有些事还看不清，别急，朦胧期也允许存在。"
        R="疑虑多半来自想象，核实一下细节就安心了。" ;;
    19) U="状态明亮，适合大胆去做想做的事。"
        R="小阴天而已，晒晒太阳、睡一觉就回晴。" ;;
    20) U="是时候给自己一个小结了，肯定过去的努力。"
        R="别急着评判自己，再给自己一点时间。" ;;
    21) U="一个小循环圆满收尾，带着收获开启下一段。"
        R="差最后一点收尾，把它完成会很舒服。" ;;
  esac
  if [ "$2" = "1" ]; then echo "$R"; else echo "$U"; fi
}

# ---------- 抽 3 张（去重） ----------
C1=$((SEED % 22))
C2=$(( (SEED / 22 + HASH) % 22 ))
C3=$(( (SEED / 22 / 22 + HASH * 7) % 22 ))
while [ "$C2" -eq "$C1" ]; do C2=$(( (C2 + 1) % 22 )); done
while [ "$C3" -eq "$C1" ] || [ "$C3" -eq "$C2" ]; do C3=$(( (C3 + 1) % 22 )); done

# 正逆位（每张独立 50%）
O1=$(( SEED % 2 ))
O2=$(( (SEED / 7) % 2 ))
O3=$(( (SEED / 13) % 2 ))

ORIENT() { if [ "$1" = "1" ]; then echo "逆位"; else echo "正位"; fi; }

# ---------- 综合提示 ----------
case $((SEED % 6)) in
  0) TIP="三张牌合起来看：先接纳过去的铺垫，再把手头这一步走稳，未来的方向会自然清晰。" ;;
  1) TIP="三张牌合起来看：你已经比想象中准备得更好，重要的是先动起来，答案会在行动里浮现。" ;;
  2) TIP="三张牌合起来看：最近适合慢一点、稳一点，给自己多一点耐心，变化会往温和的方向走。" ;;
  3) TIP="三张牌合起来看：不妨把大事拆成小决定，一件一件来，压力会轻很多。" ;;
  4) TIP="三张牌合起来看：和身边信任的人聊聊再决定，你不是一个人在面对。" ;;
  5) TIP="三张牌合起来看：今天更适合照顾情绪和身体，休息好了，思路自然会顺。" ;;
esac

# ---------- 输出 ----------
if [ -n "$QUESTION" ]; then
  echo "【塔罗三牌阵 · 过去 / 现在 / 未来】（问题：$QUESTION）"
else
  echo "【塔罗三牌阵 · 过去 / 现在 / 未来】（你没有提问题，我就为你的整体状态抽了三张）"
fi
echo "过去：$(card_name $C1)（$(ORIENT $O1)）—— $(interpret $C1 $O1)"
echo "现在：$(card_name $C2)（$(ORIENT $O2)）—— $(interpret $C2 $O2)"
echo "未来：$(card_name $C3)（$(ORIENT $O3)）—— $(interpret $C3 $O3)"
echo "综合提示：$TIP"
echo "---"
echo "娱乐免责声明：塔罗只是放松和自我反思的小游戏，牌面不预测吉凶、不代表一定会发生；医疗、财务、法律、工作等重要决定请咨询专业人士，不要依据牌面做选择。"

# v18.2 面板协议块：气泡三牌阵
echo "@qibai-panel:begin"
echo "mode=bubble"
echo "title=塔罗占卜 · 三牌阵"
echo "html=<div><b>过去</b>：$(card_name $C1)（$(ORIENT $O1)）<br/><b>现在</b>：$(card_name $C2)（$(ORIENT $O2)）<br/><b>未来</b>：$(card_name $C3)（$(ORIENT $O3)）<br/><br/>$TIP<br/><small>娱乐参考，请以现实生活为准</small></div>"
echo "@qibai-panel:end"
